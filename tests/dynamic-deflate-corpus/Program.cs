using System.Security.Cryptography;
using System.Text.Json;
using Zipelo.DynamicDeflateCorpus;

internal sealed record CaseSpec(string Id, bool Valid, int RawLength, int EndBitExclusive,
    int? OutputLength, string? OutputSha256, string? ExpectedFailure, int? FaultBitOffset, string? Control);

internal static class Program
{
    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true
    };

    public static int Main(string[] args)
    {
        if (args.Length > 1 || args.Length == 1 && args[0] != "--emit")
        {
            Console.Error.WriteLine("사용법: Zipelo.DynamicDeflateCorpus [--emit]");
            return 2;
        }
        try
        {
            var path = Path.Combine(AppContext.BaseDirectory, "expectations.json");
            var expected = JsonSerializer.Deserialize<CaseSpec[]>(File.ReadAllText(path), Options)
                ?? throw new InvalidOperationException("기대값 목록이 없음.");
            Validate(expected);
            if (args is ["--emit"])
            {
                foreach (var fixture in Corpus.Create())
                {
                    var spec = Describe(fixture);
                    Console.WriteLine(JsonSerializer.Serialize(new
                    {
                        Spec = new
                        {
                            spec.Id, spec.Valid, spec.RawLength, spec.EndBitExclusive,
                            RawSha256 = Convert.ToHexString(SHA256.HashData(fixture.Raw)),
                            spec.OutputLength, spec.OutputSha256, spec.ExpectedFailure,
                            spec.FaultBitOffset, spec.Control
                        },
                        RawHex = Convert.ToHexString(fixture.Raw),
                        fixture.Trees, fixture.Tokens, fixture.Rationale,
                        OutputPattern = fixture.Output,
                        EndKind = fixture.Valid ? "final-EOB-end" : "construction-end-not-success",
                        FinalPaddingBits = fixture.Raw.Length * 8 - fixture.EndBitExclusive,
                        DecoderObservation = (string?)null
                    }, Options));
                }
            }
            else
            {
                Console.WriteLine(JsonSerializer.Serialize(new
                {
                    Mode = "spec", Cases = expected.Length,
                    Valid = expected.Count(item => item.Valid), Invalid = expected.Count(item => !item.Valid),
                    DecoderExecuted = false, RawShaPins = "legacy literal-only only; remaining raw SHA values identify generated bytes"
                }, Options));
            }
            return 0;
        }
        catch (Exception error)
        {
            Console.Error.WriteLine($"FAIL {error.GetType().Name}: {error.Message}");
            return 1;
        }
    }

    private static CaseSpec Describe(Fixture fixture) => new(fixture.Id, fixture.Valid, fixture.Raw.Length,
        fixture.EndBitExclusive, fixture.Output?.Length, fixture.Output?.Hash(), fixture.ExpectedFailure,
        fixture.FaultBitOffset, fixture.Control);

    private static void Validate(CaseSpec[] expected)
    {
        Require(expected.Length == Corpus.Count, "고정 표본 수와 다름.");
        Require(expected.Count(item => item.Valid) == 10 && expected.Count(item => !item.Valid) == 8,
            "유효/무효 표본 수와 다름.");
        Require(expected.Select(item => item.Id).Distinct().Count() == Corpus.Count, "기대값 ID가 중복됨.");
        var found = new HashSet<string>();
        foreach (var fixture in Corpus.Create())
        {
            Require(found.Add(fixture.Id), "표본 ID가 중복됨.");
            var pin = expected.Single(item => item.Id == fixture.Id);
            Require(Describe(fixture) == pin, $"고정 명세와 다름: {fixture.Id}");
            Require(fixture.Raw.Length <= Corpus.MaxRawBytes && fixture.EndBitExclusive > 0 &&
                fixture.Raw.Length == (fixture.EndBitExclusive + 7) / 8, "입력 길이나 끝 비트가 다름.");
            Require(fixture.Output is null || fixture.Output.Length <= Corpus.MaxOutputBytes, "출력 상한을 넘음.");
            Require(fixture.Valid == (fixture.ExpectedFailure is null), "성공/실패 계약이 모순됨.");
            Require(fixture.Valid || fixture.FaultBitOffset is int fault && fault >= 0 && fault < fixture.EndBitExclusive,
                "오류 비트 위치가 없음.");
            if (fixture.Control is not null)
            {
                Require(expected.Any(item => item.Id == fixture.Control && item.Valid), "정상 대조군이 없음.");
            }
            var cursor = 0;
            foreach (var token in fixture.Tokens)
            {
                Require(token.StartBit == cursor && token.BitLength >= 0, "토큰 기록에 간격이나 중복이 있음.");
                cursor += token.BitLength;
            }
            Require(cursor == fixture.EndBitExclusive, "토큰 기록이 입력 끝까지 이어지지 않음.");
            for (var bit = cursor; bit < fixture.Raw.Length * 8; bit++)
            {
                Require(((fixture.Raw[bit / 8] >> (bit % 8)) & 1) == 0, "표본의 마지막 패딩은0이어야 함.");
            }
            if (fixture.Valid)
            {
                Require(fixture.Trees.All(tree => tree.Shape is "complete" or "single-one-bit" or "empty"),
                    "정상 표본의 트리 형태가 잘못됨.");
            }
            if (fixture.Id == "dynamic.literal-only.a")
            {
                Require(Convert.ToHexString(SHA256.HashData(fixture.Raw)) == Corpus.LegacyLiteralRawSha256,
                    "PR16 literal-only 대조군과 바이트가 다름.");
            }
        }
        Require(found.SetEquals(expected.Select(item => item.Id)), "표본 집합이 기대값과 다름.");
    }

    private static void Require(bool condition, string message)
    {
        if (!condition) { throw new InvalidOperationException(message); }
    }
}
